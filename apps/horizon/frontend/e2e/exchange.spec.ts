import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const E = require('../../../../source/assets/tools/prismo-contracts.js');
const fixture = require('../../../../packages/contracts/fixtures.json');

test('Field Kit equipment preview, undo, persistence and portable plan exchange', async ({page}) => {
  await page.goto('/');
  await page.getByRole('button', {name:'New',exact:true}).click();
  await page.getByRole('button', {name:'Radios',exact:true}).click();
  const eq = E.fromLegacy(fixture.legacy,'control','uplink');
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'Import equipment',exact:true}).click();
  await (await chooser).setFiles({name:'equipment.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(eq))});
  await expect(page.getByRole('dialog',{name:'Review equipment import'})).toBeVisible();
  await expect(page.getByText('20.0 dBm · assumed')).toBeVisible();
  await page.getByRole('button',{name:'Use equipment',exact:true}).click();
  await expect(page.getByLabel('Selected control band')).toHaveValue('fieldkit-unit-42-control');
  await page.keyboard.press('Control+z');
  await expect(page.getByLabel('Selected control band')).toHaveValue('control915');
  await page.keyboard.press('Control+Shift+z');
  await expect(page.getByLabel('Selected control band')).toHaveValue('fieldkit-unit-42-control');
  await page.waitForTimeout(800);
  await page.reload();await page.getByRole('button',{name:'Radios',exact:true}).click();
  await expect(page.getByLabel('Selected control band')).toHaveValue('fieldkit-unit-42-control');
  await page.getByRole('button',{name:'Route',exact:true}).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button',{name:'Export plan to Field Kit',exact:true}).click();
  const plan = JSON.parse(readFileSync((await (await pending).path())!, 'utf8'));
  expect(E.plan(plan).project.equipment.source_profile).toEqual(fixture.legacy);
  const oldId = plan.project.id;
  const open = page.waitForEvent('filechooser');await page.getByLabel('Open project JSON').click();
  await (await open).setFiles({name:'roundtrip.prismo-plan.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(plan))});
  await expect(page.getByLabel('Open project', {exact:true})).not.toHaveValue(oldId);
  await page.getByRole('link',{name:'PRISMO FIELD KIT'}).click();
  await expect(page.locator('#kit-bottom-nav')).toBeVisible();
  await page.locator('#kit-nav-home').click();await page.getByRole('link',{name:'Open Horizon on this computer'}).click();
  await expect(page.getByLabel('Open project', {exact:true})).toBeVisible();
});
